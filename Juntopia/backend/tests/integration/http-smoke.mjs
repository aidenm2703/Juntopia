import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { loadEnvFile } from "node:process";
import { createServer } from "node:http";
import { once } from "node:events";
import { createClient } from "@supabase/supabase-js";
import { createApp } from "../../src/app.js";
import { loadConfig } from "../../src/config/env.js";
loadEnvFile(".env.local");
const config = loadConfig(),
  users = JSON.parse(readFileSync(".test-runtime/fixtures.json", "utf8"));
const clients = users.map(() =>
  createClient(config.supabaseUrl, config.supabaseKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  }),
);
const server = createServer(createApp({ config }));
server.listen(0, "127.0.0.1");
await once(server, "listening");
const base = `http://127.0.0.1:${server.address().port}`;
const tokens = [],
  files = [];
let checks = 0;
function check(value, message) {
  assert.ok(value, message);
  checks++;
}
async function send(index, path, method = "GET", body, type) {
  const response = await fetch(base + path, {
    method,
    headers: {
      Authorization: `Bearer ${tokens[index]}`,
      Origin: "http://localhost:3000",
      ...(body === undefined
        ? {}
        : { "Content-Type": type || "application/json" }),
    },
    body: body === undefined ? undefined : type ? body : JSON.stringify(body),
  });
  return { status: response.status, payload: await response.json() };
}
async function ok(index, path, method, body, type) {
  const { status, payload } = await send(index, path, method, body, type);
  assert.equal(
    status,
    200,
    `${method || "GET"} ${path}: ${payload.error?.code || status}`,
  );
  return payload.data;
}
try {
  for (let i = 0; i < clients.length; i++) {
    const { data, error } = await clients[i].auth.signInWithPassword({
      email: users[i].email,
      password: users[i].password,
    });
    if (error) throw error;
    tokens.push(data.session.access_token);
    await ok(i, "/api/account/rpc/accept_policy", "POST", {});
    await ok(i, "/api/account/rpc/save_profile", "POST", {
      profile_data: {
        id: users[i].id,
        display_name: "HTTP Test",
        username: `http_${users[i].id.slice(0, 8)}`,
        bio: "",
        avatar_base: 0,
        avatar_color: "#a5c86a",
        interests: [],
        onboarding_step: 3,
        onboarding_complete: true,
        activity_visible: false,
      },
      visible: true,
    });
  }
  check(true, "API validates real sessions and saves profiles");
  const own = await ok(0, `/api/account/profiles/${users[0].id}`);
  check(own.id === users[0].id, "Own profile readable");
  check(
    (await ok(1, `/api/account/profiles/${users[0].id}`)) === null,
    "Other private profile hidden by RLS",
  );
  const content = await ok(0, "/api/catalog/content_items", "POST", {
    category: "Libros",
    title: "Disposable HTTP test",
    official_url: `https://example.invalid/http/${users[0].id}`,
  });
  const collection = await ok(0, "/api/library/collections", "POST", {
    title: "HTTP private collection",
  });
  check(
    (await ok(1, `/api/library/collections/${collection.id}`)) === null,
    "Private collections remain private through Node API",
  );
  check(
    (
      await send(1, "/api/library/collection_items", "POST", {
        collection_id: collection.id,
        content_id: content.id,
      })
    ).status === 403,
    "Cannot add to another user collection",
  );
  const party = await ok(0, "/api/parties/parties", "POST", {
    title: "HTTP concurrency test",
    category: "Libros",
    starts_at: new Date(Date.now() + 3600000).toISOString(),
    capacity: 2,
  });
  const answers = await Promise.all([
    ok(1, "/api/parties/rpc/set_party_rsvp", "POST", {
      target: party.id,
      answer: "going",
    }),
    ok(2, "/api/parties/rpc/set_party_rsvp", "POST", {
      target: party.id,
      answer: "going",
    }),
  ]);
  check(
    answers.includes("going") && answers.includes("waitlist"),
    "Capacity remains atomic across HTTP requests",
  );
  const saved = await ok(0, "/api/account/export");
  check(
    saved.profiles.length === 1 && saved.profiles[0].id === users[0].id,
    "Export is server-scoped to authenticated owner",
  );
  const image = Buffer.from(
    "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aDekAAAAASUVORK5CYII=",
    "base64",
  );
  const path = await ok(0, "/api/creators/files", "POST", image, "image/png");
  files.push(path);
  check(
    path.startsWith(users[0].id + "/"),
    "Upload path is generated by server for current user",
  );
  check(
    (await send(1, "/api/creators/files/signed", "POST", { path })).status ===
      404,
    "Private image cannot be signed by another user",
  );
  const signed = await ok(0, "/api/creators/files/signed", "POST", { path });
  check(
    typeof signed === "string" && signed.startsWith("https://"),
    "Owner can access signed image",
  );
  check(
    (await send(1, "/api/creators/files", "DELETE", { path })).status === 403,
    "Cannot delete another user image",
  );
  check(
    (
      await send(0, "/api/moderation/rpc/moderate_report", "POST", {
        target: crypto.randomUUID(),
        decision: "remove",
      })
    ).status === 403,
    "No moderator privilege escalation",
  );
  check(
    (await send(0, "/api/auth/password", "POST", { password: "abcdefgh" }))
      .status === 400,
    "Lowercase-only password is rejected by server",
  );
  await ok(0, "/api/auth/password", "POST", { password: "Nueva12A" });
  const changed = await clients[0].auth.signInWithPassword({
    email: users[0].email,
    password: "Nueva12A",
  });
  check(
    !changed.error && !!changed.data.session,
    "An eight-character password with an uppercase works in real Auth",
  );
  tokens[0] = changed.data.session.access_token;
  console.log(
    `HTTP real: ${checks} comprobaciones aprobadas contra Node + Supabase.`,
  );
} catch (error) {
  console.error(
    `HTTP real falló tras ${checks} comprobaciones: ${error.message}`,
  );
  process.exitCode = 1;
} finally {
  for (const path of files)
    await send(0, "/api/creators/files", "DELETE", { path }).catch(() => {});
  for (const client of clients) {
    await client.auth.signOut();
    client.realtime.disconnect();
  }
  server.closeAllConnections();
  await new Promise((resolve) => server.close(resolve));
}
